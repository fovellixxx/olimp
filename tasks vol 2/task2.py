## Задача 2. Мини-секвенсор для барабанщика 🥁
#
#Музыкант записывает барабанный ритм в виде строки:
#
#`X--X-X----X-`
#
#Каждый символ — один шаг времени:
#- `X` — удар барабана.
#- `-` — пауза.
#
#**Напиши программу**, которая получает ритм через `input()` и выводит:
#
#1. Номера шагов, на которых звучит барабан.
#2. Общее количество ударов.
#3. Длину самой длинной паузы между соседними ударами (количество `-` подряд).
#
#Шаги нумеруются с **1**. Паузы до первого и после последнего удара не учитываются. Если ударов меньше двух, длина паузы равна 0.
#
#### Пример
#
#**Ввод:**
#```text
#X--X-X----X-
#```
#
#**Вывод:**
#```text
#Удары: 1, 4, 6, 11
#Всего ударов: 4
#Самая длинная пауза: 4
#```
#
#### ⭐ Дополнительное задание
#
#Добавь второй инструмент:
#- `X` — большой барабан.
#- `O` — малый барабан.
#- `-` — пауза.
#
#Теперь программа должна отдельно выводить шаги каждого инструмента и общее количество ударов.
#
#**Ввод:**
#```text
#X-O-X-O-
#```
#
#**Вывод:**
#```text
#Большой барабан: 1, 5
#Малый барабан: 3, 7
#Всего ударов: 4
#Самая длинная пауза: 1
#```
#
#Считай, что пользователь всегда вводит непустую строку с допустимыми символами.

ritm = input('введите ритм: ')

ixy = []
oshky = []
vsebity = []

for i in range(len(ritm)):
    if ritm[i] == 'X':
        ixy.append(i+1)
        vsebity.append(i+1)
    elif ritm[i] == 'O':
        oshky.append(i+1)
        vsebity.append(i+1)

samayadlinnayapausa=0

if len(vsebity) >= 2:
    for i in range(1, len(vsebity)):
        paysa = vsebity[i] - vsebity[i-1] - 1
        if paysa > samayadlinnayapausa:
            samayadlinnayapausa = paysa

print('Большой барабан: ', *ixy)
print('Малый барабан: ', *oshky)
print('Всего ударов: ', len(vsebity))
print('Самая длинная пауза: ', samayadlinnayapausa)