"""
Задача 3. «Разбей строку на кусочки без повторов»

Условие.  
Дана строка s длиной от 1 до 1000 символов. Разбей её слева направо на несколько непустых подряд идущих подстрок по правилу:

- Начинай собирать очередной кусочек.
- Если очередная буква уже встречалась в этом кусочке, закончи кусочек перед этой буквой и начни новый кусочек с неё.
- Повторы в разных кусочках разрешены.

Выведи получившиеся кусочки через пробел.

Примеры:

s = "abba"  →  ab ba 
s = "queue" →  que ue
s = "aaaa"  →  a a a a

Как понять правило на примере abba:

1. Собираем a, затем b: получился кусочек ab.
2. Следующая буква — b. Она уже есть в текущем кусочке ab, поэтому ставим разделитель перед этой второй b.
3. Начинаем новый кусочек с этой b, затем добавляем a.

Получается ab ba. Букву, из-за которой поставили разделитель, не пропускаем — она становится первой буквой нового кусочка."""

slovo = input(': ')

podstroka = []

itog = ''

for bykva in slovo:   
    for element in podstroka:
        if bykva == element:
            itog+=' '
            podstroka=[]   
    podstroka.append(bykva)
    itog+=bykva
print(podstroka)
print(itog)
