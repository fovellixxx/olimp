"""Подстрока называется разнобуквенной, если в ней каждая буква встречается не более одного раза. Вася любит играть со словами следующим образом. Он берёт обычное слово и находит все его разбиения на подстроки так, что каждая из них является разнобуквенной.
Например, слово abba можно разбить на разнобуквенные подстроки четырьмя способами:
a b b a
ab b a
a b ba
ab ba
Однако у Васи не всегда получается правильно разбить слово. Помогите ему найти все разбиения слова queue на разнобуквенные подстроки. Подстроки в разбиении не могут быть пустыми.
Каждое разбиение записывайте в отдельное поле, добавляя их при необходимости. Подстроки выводите в порядке разбиения, разделяя пробелом. Порядок вывода разбиений неважен.
Замечание. Подстрока — это последовательность подряд идущих символов, входящих в состав данной строки.
На изображении также приведён итоговый набор корректных разбиений слова queue:
q u e u e
qu e u e
q ue u e
q u eu e
q u e ue
qu eu e
qu e ue
q ue ue
que u e
que ue
python"""

slovo=input()

variynty=[[slovo[0]]] if slovo else []

for b in slovo[1:]:
 novie_variynty=[]

 for x in variynty:
  if b not in x[-1]:novie_variynty.append(x[:-1]+[x[-1]+b])
  novie_variynty.append(x+[b])
 variynty=novie_variynty

for x in variynty:print(' '.join(x))
